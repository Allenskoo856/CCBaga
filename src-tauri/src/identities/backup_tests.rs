#[test]
fn version_0248_zstd_013_fixture_decodes_and_restores_with_current_library() {
    let digest = ring::digest::digest(&ring::digest::SHA256, LEGACY_ZSTD);
    let actual: String = digest
        .as_ref()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    assert_eq!(actual, LEGACY_ZSTD_SHA256);
    let f = Fixture::new();
    f.write(".claude/skills/keep", b"keep shared skill");
    let mut s = store::Store::open(&f.vault, &f.home).unwrap();
    let original = if cfg!(windows) {
        PathBuf::from(r"C:\__ccbaga_synthetic_legacy_home__")
    } else {
        PathBuf::from("/__ccbaga_synthetic_legacy_home__")
    };
    assert!(
        !original.exists(),
        "the fictional source home must never be used as a real directory"
    );
    let mut seal = codec::Seal::new(Vec::new(), &s.key).unwrap();
    // 压缩字节固定来自旧库；不能在测试中用当前编码器重新生成后自证兼容。
    seal.write_all(LEGACY_ZSTD).unwrap();
    let encrypted = seal.finish().unwrap();
    let record = database::Record {
        id: "00000000000000000000000000000048".into(),
        name: "Legacy synthetic".into(),
        archive: format!("{}.baga", new_id().unwrap()),
        saved_at: 0,
        bytes: encrypted.len() as u64,
        policy: Policy::default(),
        empty: false,
        account_key: None,
    };
    private::write(&f.vault.join(&record.archive), &encrypted).unwrap();
    // 先按原始 v1 来源验收，再只在测试内重定位到私有夹具，绝不写来源绝对路径。
    s.home = original.clone();
    let mut stage = s.load(&record).unwrap();
    s.home = f.home.clone();
    for source in &mut stage.manifest.sources {
        source.path = f.home.join(source.path.strip_prefix(&original).unwrap());
    }
    stage.manifest.home = f.home.clone();
    let active = s.db.get("active").unwrap();
    s.restore(
        &stage,
        &store::Store::selected(&stage, &Policy::default()),
        &Policy::default(),
        &Reporter::channel(None),
        "restore",
    )
    .unwrap();
    assert_eq!(f.token(), "legacy-synthetic-token");
    assert_eq!(
        fs::read(f.home.join(".claude/history.jsonl")).unwrap(),
        b"legacy-synthetic-history\n"
    );
    assert_eq!(
        fs::read(f.home.join(".claude/skills/keep")).unwrap(),
        b"keep shared skill"
    );
    assert_eq!(
        profile::read(&f.home).display_name.as_deref(),
        Some("Legacy Fixture")
    );
    assert_eq!(s.db.get("active").unwrap(), active);
    assert!(!original.exists());
}

#[test]
fn backup_of_manually_changed_cli_identity_keeps_browser_mismatch_and_active_pointer() {
    let f = Fixture::new();
    let p = Policy::default();
    let r = Reporter::channel(None);
    let mut s = store::Store::open(&f.vault, &f.home).unwrap();
    s.db.configure_browser(true, false, None).unwrap();
    f.login("A", "one", "a-token");
    s.switch("empty", "A", &p, &r).unwrap();
    let a = s.records()[0].id.clone();
    f.login("B", "one", "b-token");
    s.switch(&a, "B", &p, &r).unwrap();
    let b = s.records().into_iter().find(|row| row.id != a).unwrap().id;
    let a_slot = s.db.browser_slot().unwrap();
    let b_slot = s.db.browser_for(&b).unwrap().unwrap();
    assert_ne!(a_slot, b_slot);
    f.login("B", "one", "b-refreshed");
    s.save_current("B backup", &p, &r).unwrap();
    assert_eq!(f.token(), "b-refreshed");
    assert_eq!(s.db.get("active").unwrap().as_deref(), Some(a.as_str()));
    assert_eq!(s.db.browser_slot().unwrap(), a_slot);
    assert_eq!(s.db.browser_for(&b).unwrap().unwrap(), b_slot);
    assert_eq!(
        catalog::current_id(&f.vault, &f.home, &s.db).unwrap(),
        Some(b)
    );
    assert_eq!(
        s.db.browser_identity(&f.vault, &f.home).unwrap().status,
        "mismatch"
    );
}

#[test]
