#[test]
fn transient_locks_are_not_archived_or_restored_but_unknown_directory_data_is_preserved() {
    let f = Fixture::new();
    f.login("A", "one", "a-token");
    f.write(".claude.lock", b"transient lock");
    private::directory(&f.home.join(".claude.json.lock")).unwrap();
    f.write(".claude/daemon.lock/important", b"unknown user data");
    let mut s = store::Store::open(&f.vault, &f.home).unwrap();
    let p = Policy::default();
    let r = Reporter::channel(None);
    let (mut record, mut stage) = s.save("A", &p, &r).unwrap();
    assert!(!stage
        .manifest
        .sources
        .iter()
        .any(|src| src.path == f.home.join(".claude.lock")
            || src.path == f.home.join(".claude.json.lock")));
    assert!(stage
        .manifest
        .sources
        .iter()
        .any(|src| src.path == f.home.join(".claude/daemon.lock")));
    // 构造合法认证的旧版本归档，其中仍有普通锁文件和空锁目录。
    for (relative, directory) in [(".claude.lock", false), (".claude.json.lock", true)] {
        let n = stage.manifest.sources.len();
        let path = stage.path.join(format!("data/{n}"));
        if directory {
            private::directory(&path).unwrap();
        } else {
            private::write(&path, b"old transient lock").unwrap();
        }
        stage
            .manifest
            .sources
            .push(crate::cleaner::identity::Source {
                path: f.home.join(relative),
                category: "cache".into(),
                keys: Vec::new(),
            });
        stage.manifest.fingerprints.push(Vec::new());
    }
    s.switch("empty", "A", &p, &r).unwrap();
    record.archive = format!("{}.baga", new_id().unwrap());
    let seal = codec::Seal::new(
        private::create(&f.vault.join(&record.archive)).unwrap(),
        &s.key,
    )
    .unwrap();
    let mut tar = tar::Builder::new(compression::encode(seal).unwrap());
    for n in 0..stage.manifest.sources.len() {
        let data = stage.path.join(format!("data/{n}"));
        archive::walk(&data, &data, &mut |path, relative, directory| {
            let target = Path::new("data").join(n.to_string());
            let target = if relative.as_os_str().is_empty() {
                target
            } else {
                target.join(relative)
            };
            if directory {
                tar.append_dir(target, path)
            } else {
                tar.append_file(target, &mut fs::File::open(path).unwrap())
            }
            .map_err(store::problem)
        })
        .unwrap();
    }
    let bytes = serde_json::to_vec(&stage.manifest).unwrap();
    let mut header = tar::Header::new_gnu();
    header.set_size(bytes.len() as u64);
    header.set_mode(0o600);
    header.set_cksum();
    tar.append_data(&mut header, "manifest.json", &bytes[..])
        .unwrap();
    tar.into_inner()
        .unwrap()
        .finish()
        .unwrap()
        .finish()
        .unwrap()
        .sync_all()
        .unwrap();
    s.db.remember(&record).unwrap();
    drop(stage);
    assert!(!f.home.join(".claude/daemon.lock").exists());
    assert!(f.home.join(".claude.lock").exists());
    fs::remove_file(f.home.join(".claude.lock")).unwrap();
    fs::remove_dir(f.home.join(".claude.json.lock")).unwrap();
    let legacy = s.load(&record).unwrap();
    assert_eq!(
        store::Store::selected(&legacy, &p).len() + 2,
        legacy.manifest.sources.len()
    );
    drop(legacy);
    s.switch(&record.id, "Empty", &p, &r).unwrap();
    assert!(!f.home.join(".claude.lock").exists());
    assert!(!f.home.join(".claude.json.lock").exists());
    assert_eq!(
        fs::read(f.home.join(".claude/daemon.lock/important")).unwrap(),
        b"unknown user data"
    );
    assert_eq!(f.token(), "a-token");
}

