    let old = s.records()[0].clone();
    let slot = s.db.browser_slot().unwrap();
    s.db.connection.execute_batch("CREATE TRIGGER reject_summary BEFORE UPDATE ON identity_summaries BEGIN SELECT RAISE(ABORT,'fixture'); END;").unwrap();
